def build_pipeline_runs(now: datetime) -> list[dict[str, Any]]:
    """按当前时间把偏移量换算成真实时间戳，保证窗口判断始终可复现。"""
    rows: list[dict[str, Any]] = []
    for index, tpl in enumerate(PIPELINE_RUN_TEMPLATE, start=1):
        started_at = now + timedelta(seconds=tpl["偏移秒"])
        rows.append({
            "id": index,
            "节点编号": tpl["节点编号"],
            "开始时间": started_at.isoformat(),
            "耗时毫秒": tpl["耗时毫秒"],
            "吞吐条分": tpl["吞吐条分"],
            "错误数": tpl["错误数"],
            "窗口内": tpl["偏移秒"] >= -WINDOW_MINUTES * 60,
        })
    return rows


